const built = new Map<GalleryData, ReviewDataset>();

export const reviewDataset = (data: GalleryData): ReviewDataset => {
  const known = built.get(data);

  if (known !== undefined) return known;
  const made = builders[data]();

  built.set(data, made);

  return made;
};
