interface FindingInput {
  readonly severity: RiskFinding["severity"];
  readonly path: string;
  readonly line: number;
  readonly title: string;
  readonly reason?: string;
  readonly side?: "new" | "old";
  readonly status?: RiskFinding["status"];
  readonly confidence?: number;
}

const finding = (id: string, input: FindingInput) =>
  new RiskFinding({
    id: RiskFindingId.make(id),
    identity: id,
    source: input.severity === "critical" ? "rule" : "agent",
    ruleId: null,
    path: input.path,
    lines: new LineRange({ start: input.line, end: input.line, side: input.side ?? "new" }),
    severity: input.severity,
    confidence: input.confidence ?? 0.9,
    title: input.title,
    reason: input.reason ?? "The reviewer flagged this line.",
    suggestion: null,
    status: input.status ?? "open",
    resolution: null,
  });

