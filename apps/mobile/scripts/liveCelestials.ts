/**
 * Writes targets/widgets/LiveCelestials.swift: each planet at rest from @polaris/ui's cells,
 * and each hued Harness's four tones as the app mixes them. live.celestials.test.ts checks.
 */
import { CELESTIAL_PLANETS, HARNESS_CATALOGUE } from "@polaris/protocol";
import { type Cell, celestialCells, type Tone } from "@polaris/ui/celestial";
import { celestialPalette, harnessColour } from "../src/celestial/tones.ts";
import { themes } from "../src/theme/appearance.ts";

export const LIVE_CELESTIALS_PATH = new URL(
  "../targets/widgets/LiveCelestials.swift",
  import.meta.url
).pathname;

const TONES: ReadonlyArray<Tone> = ["light", "hue", "shade", "glint"];

/** Each row's same-tone neighbours as one run: [x, y, width, tone]. */
const runs = (cells: ReadonlyArray<Cell>): number[] => {
  const out: number[] = [];
  const sorted = [...cells].sort((a, b) => a.y - b.y || a.x - b.x);

  for (const cell of sorted) {
    const at = out.length - 4;
    const tone = TONES.indexOf(cell.tone);

    const extends_ =
      at >= 0 &&
      out[at + 1] === cell.y &&
      out[at + 3] === tone &&
      (out[at] ?? 0) + (out[at + 2] ?? 0) === cell.x;

    if (extends_) out[at + 2] = (out[at + 2] ?? 0) + 1;
    else out.push(cell.x, cell.y, 1, tone);
  }

  return out;
};

const hex = (colour: string) => `0x${colour.slice(1, 7).toUpperCase()}`;

const tones = (hue: string) => {
  const palette = celestialPalette(hue);

  return `[${TONES.map((tone) => hex(palette[tone])).join(", ")}]`;
};

export const liveCelestialsSwift = (): string => {
  const colours = themes.midnight;

  const bodies = CELESTIAL_PLANETS.map(
    (body) => `  "${body}": [${runs(celestialCells(body)).join(", ")}],`
  );

  const hued = HARNESS_CATALOGUE.filter(
    (entry) => harnessColour(colours, entry.kind) !== colours.textSubtle
  ).map((entry) => `  "${entry.kind}": ${tones(harnessColour(colours, entry.kind))},`);

  return [
    "// Generated by scripts/liveCelestials.ts from @polaris/ui's celestials and the Harness hues;",
    "// don't edit. Run `bun scripts/liveCelestials.ts` after changing either.",
    "",
    "/// Each planet at rest on a 16 grid, as runs of [x, y, width, tone]: light, hue, shade, glint.",
    "let liveBodies: [String: [UInt8]] = [",
    ...bodies,
    "]",
    "",
    "/// Each hued Harness's tones (light, hue, shade, glint), the same in both themes.",
    "let liveHarnessTones: [String: [UInt32]] = [",
    ...hued,
    "]",
    "",
    "/// An unknown or unhued Harness: text-subtle's tones.",
    `let liveNeutralTones: [UInt32] = ${tones(colours.textSubtle)}`,
    "",
  ].join("\n");
};

if (import.meta.main) await Bun.write(LIVE_CELESTIALS_PATH, liveCelestialsSwift());
