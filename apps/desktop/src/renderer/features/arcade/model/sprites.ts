export const spriteWidth = (sprite: Sprite) => sprite[0]?.length ?? 0;

/** The lit cells of a sprite, relative to its top-left. */
export const litCells = (sprite: Sprite): ReadonlyArray<readonly [number, number]> =>
  sprite.flatMap((row, y) =>
    row.split("").flatMap((ch, x) => (ch === "#" ? [[x, y] as const] : []))
  );
