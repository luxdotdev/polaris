#!/usr/bin/env bun
/**
 * Re-vendors Chart.js and D3 into `src/vendor/` from their npm tarballs.
 *
 *   bun scripts/vendor.ts
 *
 * Refuses a file whose sha256 differs from `src/vendor/pins.ts`: to upgrade, change the pin (version,
 * file and hash) and the README's table in the same commit, then run this.
 */
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { sha256Hex } from "../src/vendor/hash.ts";
import { LIBRARY_PINS, type LibraryPin } from "../src/vendor/pins.ts";

const root = join(import.meta.dir, "..");

const run = (command: string, args: ReadonlyArray<string>, cwd: string): void => {
  const result = spawnSync(command, args, { cwd, stdio: "inherit" });

  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} failed`);
};

/** A template literal body: the text back byte for byte once the module is evaluated. */
const templateBody = (text: string): string =>
  text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");

const vendor = (pin: LibraryPin): void => {
  const dir = mkdtempSync(join(tmpdir(), `pv-${pin.module}-`));
  run("npm", ["pack", `${pin.npm}@${pin.version}`, "--silent"], dir);
  run("tar", ["xzf", `${pin.npm.replaceAll("/", "-")}-${pin.version}.tgz`], dir);
  const source = readFileSync(join(dir, "package", pin.file), "utf8");
  const hash = sha256Hex(source);

  if (hash !== pin.sha256) {
    throw new Error(`${pin.npm}@${pin.version} ${pin.file} is ${hash}, pinned ${pin.sha256}`);
  }

  writeFileSync(
    join(root, "vendor", pin.licenseFile),
    readFileSync(join(dir, "package", pin.upstreamLicense))
  );
  const header = `// Generated by scripts/vendor.ts from ${pin.npm}@${pin.version} ${pin.file} (${pin.license}); do not edit.\n`;
  writeFileSync(
    join(root, "src", "vendor", `${pin.module}.ts`),
    `${header}export const source = \`${templateBody(source)}\`;\n`
  );
  console.log(`${pin.npm}@${pin.version}: ${source.length} chars, sha256 ${hash}`);
};

for (const pin of LIBRARY_PINS) vendor(pin);
